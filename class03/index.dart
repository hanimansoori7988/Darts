void main() {
  // for loop
 for (int i = 0; i <= 10; i++) {
    for (int j = 1; j <= 2; j++) {
      // print('i:$i,j:$j');
      print('$i , $j');
    }
  }
  // while loop
  print("while loop");
  int k =5;
  int m=4;
  while(k>2){
    while(m>3){
      print(m);
      m--;
    }
    print(k);
    k--;
  }
}
